export function scoreTest(answers) {
  const byType = Object.fromEntries(Object.keys(TYPES).map((k) => [k, 0]));
  let total = 0;
  QUESTIONS.forEach((q, i) => {
    const v = answers[i] ?? 0;
    byType[q.type] += v;
    total += v;
  });
  // 동점이면 문항 순서상 먼저 나온 유형을 우선한다.
  const ranked = Object.entries(byType).sort((a, b) => b[1] - a[1]);
  const level = LEVELS.find((l) => total <= l.max) ?? LEVELS[LEVELS.length - 1];
  return { type: ranked[0][0], second: ranked[1][0], byType, total, level: level.key };
}
